  @override
  Future<List<FmStation>> getStations() async {
    await Future.delayed(const Duration(milliseconds: 300));

    final favorites = await FavoriteStationStorage.getFavorites();

    final stations = _mockStations
        .map(
          (station) => station.copyWith(
            isFavorite: favorites.contains(station.id),
          ),
        )
        .toList();

    stations.sort((a, b) {
      if (a.id == 'delta_fm_live') return -1;
      if (b.id == 'delta_fm_live') return 1;

      if (a.isFavorite != b.isFavorite) {
        return a.isFavorite ? -1 : 1;
      }

      return b.listeners.compareTo(a.listeners);
    });

    return stations;
  }

  @override
  Future<List<FmStation>> getFavoriteStations() async {
    final stations = await getStations();
    return stations.where((s) => s.isFavorite).toList();
  }

  @override
  Future<List<FmStation>> searchStations(String query) async {
    await Future.delayed(const Duration(milliseconds: 300));
    final q = query.trim().toLowerCase();
    
    if (q.isEmpty) {
      return getStations();
    }

    return _mockStations.where((s) =>
        s.name.toLowerCase().contains(q) ||
        s.country.toLowerCase().contains(q) ||
        s.type.toLowerCase().contains(q) ||
        s.city.toLowerCase().contains(q) ||
        s.category.toLowerCase().contains(q) ||
        s.language.toLowerCase().contains(q) ||
        s.frequency.toLowerCase().contains(q) ||
        s.currentProgram.toLowerCase().contains(q) ||
        s.description.toLowerCase().contains(q)
    ).toList();
  }

  @override
  Future<FmStation?> getStationById(String id) async {
    await Future.delayed(const Duration(milliseconds: 100));
    try {
      return _mockStations.firstWhere((s) => s.id == id);
    } catch (_) {
      return null;
    }
  }

  @override
  Future<void> toggleFavorite(String id) async {
    await FavoriteStationStorage.toggle(id);

    final favorites = await FavoriteStationStorage.getFavorites();

    final index = _mockStations.indexWhere((e) => e.id == id);

    if (index != -1) {
      _mockStations[index] = _mockStations[index].copyWith(
        isFavorite: favorites.contains(id),
      );
    }
  }

