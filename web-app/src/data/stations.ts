export const getStationById = (id: string): FmStation | undefined => {
  return fmStations.find(s => s.id === id);
};

export const getStationsByType = (type: string): FmStation[] => {
  return fmStations.filter(s => s.type === type);
};

export const getStationsByCountry = (country: string): FmStation[] => {
  return fmStations.filter(s => s.country === country);
};

export const searchStations = (query: string): FmStation[] => {
  const q = query.toLowerCase();
  return fmStations.filter(s =>
    s.name.toLowerCase().includes(q) ||
    s.country.toLowerCase().includes(q) ||
    s.category.toLowerCase().includes(q) ||
    s.city.toLowerCase().includes(q)
  );
};
